//! Render bundled evidence without inspecting a host, skill store or environment.
use agent_skills_kit::catalog::{Catalog, ContextBase, PathBase, PathRule};
fn context(base: ContextBase) -> &'static str {
    match base {
        ContextBase::Home => "home",
        ContextBase::Project => "project",
        ContextBase::ApplicationWorkspace => "application_workspace",
        _ => "unknown_context",
    }
}
fn append(base: &str, components: &[String]) -> String {
    if components.is_empty() {
        base.to_owned()
    } else {
        format!("{base}/{}", components.join("/"))
    }
}
fn path(rule: &PathRule) -> String {
    match &rule.base {
        PathBase::Home => append("home", &rule.components),
        PathBase::Project => append("project", &rule.components),
        PathBase::ApplicationWorkspace => append("application_workspace", &rule.components),
        PathBase::Environment { variable, fallback } => {
            let primary = append(&format!("env:{variable}"), &rule.components);
            fallback.as_ref().map_or(primary.clone(), |fallback| {
                format!(
                    "{primary}; absent-only fallback {}",
                    append(
                        &append(context(fallback.base), &fallback.components),
                        &rule.components
                    )
                )
            })
        }
        _ => "unverified base".into(),
    }
}
fn cell(text: &str) -> String {
    text.replace('|', "\\|")
        .replace(['\r', '\n'], " ")
        .replace('`', "&#96;")
}
fn main() -> Result<(), Box<dyn std::error::Error>> {
    let catalog = Catalog::bundled()?;
    println!("# Bundled target evidence matrix\n");
    println!(
        "**WIP — not ready for use.** This matrix records development evidence, not a released library/CLI or validated real-host support.\n"
    );
    println!(
        "Generated by `cargo run --quiet -p agent-skills-kit --example catalog_markdown --locked`. Regenerate rows from bundled data.\n"
    );
    println!(
        "Roots are explicit caller context, not discovered HOME or current directories. Scope status describes documentation classification; platform arrays/test IDs are resolver evidence, not actual host discovery or universal OS/version support. Exact native CI results belong to each final-SHA QA record.\n"
    );
    println!(
        "The discovery column reflects bundled records only. [Opt-in host smoke results](verification/host-discovery.md) separately record exact versions, OS/scopes, failed attempts and unrun procedures; a bounded sample does not establish other host combinations.\n"
    );
    println!(
        "| Target / product / variant | Scope status / resolver platforms | Preferred write | Readable locations (declared order) | Primary review / resolver evidence | Real-host discovery |"
    );
    println!("| --- | --- | --- | --- | --- | --- |");
    for target in catalog.targets() {
        for scope in &target.scopes {
            let preferred = scope.preferred_write.as_ref();
            let write = preferred.map_or_else(
                || "unavailable".into(),
                |rule| format!("`{}`", cell(&path(&rule.path))),
            );
            let reads = scope
                .discovery
                .iter()
                .map(|location| {
                    format!(
                        "`{}` ({:?})",
                        cell(&path(&location.location.path)),
                        location.traversal
                    )
                })
                .collect::<Vec<_>>()
                .join("<br>");
            let review = preferred.map_or_else(
                || "unverified".into(),
                |rule| {
                    rule.evidence.source.as_ref().map_or_else(
                        || "no primary source".into(),
                        |source| {
                            format!(
                                "[{}]({}); {}; {} named resolver tests",
                                cell(&source.section),
                                source.url,
                                source.accessed,
                                rule.evidence.resolver_tests.len()
                            )
                        },
                    )
                },
            );
            let discovery =
                if preferred.is_some_and(|rule| !rule.evidence.discovery_tests.is_empty()) {
                    "recorded; inspect evidence"
                } else {
                    "unverified"
                };
            println!(
                "| `{}` / `{}` / `{}` | {:?} / {:?} / {:?} | {} | {} | {} | {} |",
                target.id,
                target.product_id,
                target.variant,
                scope.scope,
                scope.status,
                scope.platforms,
                write,
                reads,
                review,
                discovery
            );
        }
    }
    println!(
        "\nSee [catalog review](catalog.md) for precedence, overrides, reservation/variant gaps and source applicability. A successful directory copy never proves that the real host loads it."
    );
    Ok(())
}
